/**
 * Games section: renders the pipeline's index and drives build / preview / inspect actions.
 *
 * Loaded as a classic script after app.js and self-initialising, so it shares the page's helpers
 * (which are script-scoped globals there) without needing to be woven into the portal's own boot
 * sequence. Every action degrades explicitly: what needs the desktop shell is marked as such rather
 * than silently doing nothing.
 */
'use strict';

(function initGamesSection() {
  const GRID = document.getElementById('gameGrid');
  if (!GRID) return;

  const EMPTY = document.getElementById('gamesEmpty');
  const REFRESH = document.getElementById('btnGamesRefresh');
  const bridge = window.portalAPI || null;
  const isDesktop = Boolean(bridge && bridge.isDesktop);

  /** State badge copy, keyed by the readiness ladder the index script measures. */
  const STATE_LABEL = {
    discoverable: 'Distribution-only scaffold',
    buildable: 'Buildable',
    runnable: 'Runnable',
    failed: 'Failed build',
  };

  let games = [];
  let summary = null;
  /** ids currently building or launching, so buttons can be disabled without a global spinner. */
  const busy = new Set();

  const fmtBytes = (bytes) => {
    if (!Number.isFinite(bytes) || bytes <= 0) return '—';
    if (bytes < 1024) return `${bytes} B`;
    if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
    return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
  };

  const fmtDate = (iso) => {
    if (!iso) return 'never built';
    const date = new Date(iso);
    return Number.isNaN(date.getTime()) ? 'never built' : date.toLocaleString();
  };

  const esc = (value) => String(value == null ? '' : value).replace(/[&<>"']/g, (char) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));

  /**
   * Reuse the portal's own toast helper (a script-scoped global from app.js) so notifications look
   * and behave identically here. Its `kind` vocabulary is 'err' | 'ok'.
   */
  function notify(message, detail, kind) {
    const mapped = kind === 'error' ? 'err' : kind === 'info' ? 'ok' : undefined;
    if (typeof window.toast === 'function') {
      window.toast(message, detail, mapped);
      return;
    }
    // The portal helpers were unavailable (e.g. the file was loaded standalone): still report.
    console.log(`[games] ${message}`, detail || '');
  }

  async function loadGames(force) {
    try {
      const url = `./data/games.json${force ? `?t=${Date.now()}` : ''}`;
      const response = await fetch(url, { cache: 'no-store' });
      if (!response.ok) throw new Error(`games.json HTTP ${response.status}`);
      const payload = await response.json();
      games = Array.isArray(payload.games) ? payload.games : [];
      summary = payload;
    } catch (error) {
      games = [];
      summary = null;
      renderError(error);
      return;
    }
    render();
  }

  function renderError(error) {
    GRID.innerHTML = '';
    const card = document.createElement('article');
    card.className = 'card';
    card.innerHTML = `<h3>Game index unavailable</h3>
      <p class="desc">${esc(String((error && error.message) || error))}. The index is generated by
      <code>npm run games:build</code>; it is not present until a build has run.</p>`;
    GRID.appendChild(card);
  }

  function actionButton(label, action, extra) {
    const classes = extra && extra.primary ? 'btn small btn-primary' : 'btn small';
    const locked = extra && extra.desktopOnly && !isDesktop;
    return `<button class="${classes}" data-game-act="${action}"${locked ? ' data-desktop-only="1"' : ''}>${esc(label)}</button>`;
  }

  function render() {
    GRID.innerHTML = '';
    if (EMPTY) EMPTY.hidden = games.length > 0;

    if (summary && summary.totals) {
      const stats = document.getElementById('gamesStats');
      if (stats) {
        stats.innerHTML = `
          <li><span class="stat-value">${summary.totals.projects}</span><span class="stat-label">projects</span></li>
          <li><span class="stat-value">${summary.totals.built}</span><span class="stat-label">built</span></li>
          <li><span class="stat-value">${summary.totals.assets}</span><span class="stat-label">assets</span></li>
          <li><span class="stat-value">${fmtBytes(summary.totals.outputBytes)}</span><span class="stat-label">build output</span></li>`;
      }
    }

    for (const game of games) {
      const card = document.createElement('article');
      card.className = 'card';
      card.dataset.gameId = game.id;
      card.dataset.state = game.state;
      card.dataset.busy = busy.has(game.id) ? '1' : '0';

      const warnings = game.warnings || [];
      const errors = game.errors || [];
      const issueList = [
        ...errors.slice(0, 3).map((issue) => `<li class="issue-error">${esc(issue.code)}: ${esc(issue.message)}</li>`),
        ...warnings.slice(0, 3).map((issue) => `<li class="issue-warn">${esc(issue.code)}: ${esc(issue.message)}</li>`),
      ].join('');

      card.innerHTML = `
        <div class="card-head">
          <h3>${esc(game.name)}</h3>
          <span class="badge">${esc(STATE_LABEL[game.state] || game.state)}</span>
        </div>
        <p class="kind">${esc(game.id)} · v${esc(game.version)} · engine ${esc(game.engine)}</p>
        <p class="desc">${esc(game.description || 'No description provided.')}</p>
        <div class="chips">
          <span class="chip">${esc(game.width)}×${esc(game.height)}</span>
          <span class="chip">${game.bundles.length} bundles</span>
          <span class="chip">${game.assetCount} assets</span>
          <span class="chip">${fmtBytes(game.distBytes)}</span>
          ${game.tags.map((tag) => `<span class="chip">#${esc(tag)}</span>`).join('')}
        </div>
        <div class="bars">
          ${game.bundles.map((bundle) => `
            <div class="bar-row">
              <span title="${esc(bundle.file)}">${esc(bundle.file)}</span>
              <span class="track"><span class="fill" style="width:${Math.max(3, Math.min(100, Math.round((bundle.bytes / (game.bundles[0]?.bytes || 1)) * 100)))}%"></span></span>
              <span>${fmtBytes(bundle.bytes)}</span>
            </div>`).join('') || '<div class="bar-row"><span>no bundles</span><span class="track"></span><span>—</span></div>'}
        </div>
        ${issueList ? `<ul class="issue-list">${issueList}</ul>` : ''}
        <p class="note">Last build ${esc(fmtDate(game.builtAt))}${game.durationMs ? ` (${game.durationMs} ms)` : ''}</p>
        <div class="card-actions">
          ${actionButton(game.built ? 'Rebuild' : 'Build', 'build', { primary: true, desktopOnly: true })}
          ${actionButton(game.built ? 'Play' : 'Preview', 'preview', { primary: !isDesktop && Boolean(playUrl(game)) })}
          ${actionButton('Stop', 'stop', { desktopOnly: true })}
          ${actionButton('Validate', 'validate', { desktopOnly: true })}
          ${actionButton('Logs', 'logs', { desktopOnly: true })}
          ${actionButton('Source', 'source', { desktopOnly: true })}
          ${actionButton('Open build', 'buildFolder', { desktopOnly: true })}
        </div>`;

      const game_ = game;
      card.querySelectorAll('[data-game-act]').forEach((button) => {
        const action = button.dataset.gameAct;
        if (button.dataset.desktopOnly && !isDesktop) {
          button.classList.add('is-locked');
          button.title = 'Available in the packaged desktop app';
        }
        button.addEventListener('click', () => onAction(action, game_, card, button));
      });

      GRID.appendChild(card);
    }
  }

  /**
   * Where a browser can play this game, or null. The hosted site publishes each built game under
   * play/<id>/ and records it as game.playPath; the value is resolved against the page so it also
   * works when the portal is served from a sub-path (GitHub Pages) and is only followed when it
   * stays on this origin and inside play/.
   */
  function playUrl(game) {
    if (typeof game.playPath !== 'string' || !game.playPath) return null;
    try {
      const url = new URL(game.playPath, document.baseURI);
      return url.origin === window.location.origin && /\/play\/[a-z0-9-]+\/$/.test(url.pathname) ? url.href : null;
    } catch {
      return null;
    }
  }

  /** Preview in browser mode. Hosted builds use playPath; the dev server falls back to the dist folder. */
  function openBuildInTab(game) {
    const hosted = playUrl(game);
    if (hosted) {
      window.open(hosted, '_blank', 'noopener');
      return;
    }
    if ('playPath' in game) {
      // The index came from a hosted build that did not publish this game: say so instead of 404ing.
      notify('Not available on this site', `${game.name} has no published build here. Rebuild the site with npm run games:build then npm run pwa:build.`, 'warn');
      return;
    }
    window.open(`./${game.distDir}/`, '_blank', 'noopener');
  }

  async function onAction(action, game, card, button) {
    if (button.dataset.desktopOnly && !isDesktop) {
      notify('Desktop app required', `${action} runs through the packaged shell's allow-listed actions.`, 'warn');
      return;
    }

    if (action === 'preview' && !isDesktop) {
      if (!game.built) {
        notify('Not built yet', 'Build the game first, or run npm run games:build.', 'warn');
        return;
      }
      openBuildInTab(game);
      return;
    }

    button.disabled = true;
    const restore = () => { button.disabled = false; };
    busy.add(game.id);
    card.dataset.busy = '1';

    try {
      const result = await bridge.invoke(`game:${action}`, { id: game.id });
      if (result && result.ok === false) {
        notify(`${action} failed`, result.message || 'See the log for details.', 'error');
      } else if (action === 'build') {
        const report = result.report || {};
        notify(
          report.status === 'success' ? `${game.name} built` : `${game.name} build failed`,
          report.status === 'success'
            ? `${report.outputs.length} files, ${fmtBytes(report.outputBytes)} in ${report.durationMs} ms`
            : (report.errors && report.errors[0] ? report.errors[0].message : 'See the log for details.'),
          report.status === 'success' ? 'info' : 'error',
        );
      } else if (action === 'validate') {
        notify(
          result.valid ? `${game.name} is valid` : `${game.name} has problems`,
          result.message || '',
          result.valid ? 'info' : 'warn',
        );
      } else if (action === 'logs') {
        showLogs(game, result);
      } else if (action === 'preview') {
        notify(`${game.name} launched`, result.message || 'Opening in a game window.', 'info');
      } else if (result && result.message) {
        notify(`${action} done`, result.message, 'info');
      }
    } catch (error) {
      notify(`${action} failed`, String((error && error.message) || error), 'error');
    } finally {
      busy.delete(game.id);
      card.dataset.busy = '0';
      restore();
      // A build changes the index; a validate does not need a refresh.
      if (action === 'build') await loadGames(true);
    }
  }

  /** Show a build's report or recent log lines in a lightweight overlay. */
  function showLogs(game, result) {
    const existing = document.getElementById('gameLogOverlay');
    if (existing) existing.remove();

    const overlay = document.createElement('div');
    overlay.id = 'gameLogOverlay';
    overlay.className = 'drawer-scrim';
    const panel = document.createElement('div');
    panel.className = 'drawer log-drawer';
    panel.setAttribute('role', 'dialog');
    panel.setAttribute('aria-label', `${game.name} logs`);
    panel.innerHTML = `
      <header class="drawer-head">
        <h2>${esc(game.name)} — logs</h2>
        <button class="btn small" type="button" data-close="1">Close</button>
      </header>
      <div class="drawer-body"><pre class="log-view"></pre></div>`;

    const pre = panel.querySelector('.log-view');
    const lines = (result && result.lines) || [];
    pre.textContent = lines.length > 0
      ? lines.join('\n')
      : 'No build log recorded yet. Build the game to produce a report.';

    overlay.appendChild(panel);
    document.body.appendChild(overlay);
    const close = () => overlay.remove();
    overlay.addEventListener('click', (event) => { if (event.target === overlay) close(); });
    panel.querySelector('[data-close]').addEventListener('click', close);
  }

  /**
   * Live state from a launched game window: the runtime shell reports through the `gameforge`
   * bridge, the main process forwards it here, and the card shows it. This is what makes "launch
   * a game and inspect it" real rather than a screenshot.
   */
  function subscribeToRuntime() {
    if (!isDesktop || typeof bridge.onGameRuntime !== 'function') return;
    bridge.onGameRuntime(({ id, state } = {}) => {
      if (!id || !state) return;
      const card = GRID.querySelector(`[data-game-id="${id}"]`);
      const note = card && card.querySelector('.note');
      if (!note) return;
      note.dataset.live = '1';
      note.textContent = `Running — ${state.fps ?? '?'} fps · ${state.entities ?? '?'} entities · ${state.drawCalls ?? '?'} draws · scene ${state.activeScene ?? '—'}`;
    });
  }

  REFRESH?.addEventListener('click', () => {
    notify('Refreshing index', 'Re-reading games.json from disk.', 'info');
    void loadGames(true);
  });

  // A build started elsewhere (CLI, CI) is picked up when the window regains focus.
  window.addEventListener('focus', () => { void loadGames(false); });

  subscribeToRuntime();
  void loadGames(false);
})();
